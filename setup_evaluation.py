#!/usr/bin/env python3
"""
Setup script for RAG & LLM Evaluation Environment

This script helps you:
1. Install missing packages
2. Set up environment variables
3. Verify the setup

Usage:
    python setup_evaluation.py
"""

import os
import sys
import subprocess
from pathlib import Path

def print_header(text):
    """Print a formatted header."""
    print("\n" + "="*60)
    print(f"  {text}")
    print("="*60 + "\n")

def install_packages():
    """Install missing Python packages."""
    print_header("📦 Installing Required Packages")
    
    packages = ['rouge-score', 'pdfplumber']
    
    for package in packages:
        try:
            print(f"Installing {package}...", end=" ")
            subprocess.check_call(
                [sys.executable, '-m', 'pip', 'install', package, '-q'],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL
            )
            print("✅")
        except subprocess.CalledProcessError:
            print(f"❌ Failed to install {package}")
            print(f"Try manually: pip install {package}")

def setup_env_file():
    """Set up .env file with API keys."""
    print_header("🔐 Setting Up Environment Variables")
    
    env_file = Path('.env')
    env_vars = {}
    
    # Load existing .env if it exists
    if env_file.exists():
        print("✅ Found existing .env file")
        print("   (Will update or append values)\n")
        with open(env_file, 'r') as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith('#') and '=' in line:
                    key, value = line.split('=', 1)
                    env_vars[key] = value
    else:
        print("📝 Creating new .env file\n")
    
    # Prompt for values
    print("Please provide your configuration:")
    print("(Press Enter to keep existing value or skip)\n")
    
    # PINECONE_API_KEY
    current = env_vars.get('PINECONE_API_KEY', '')
    if current:
        print(f"Current PINECONE_API_KEY: {current[:10]}...{current[-4:]}")
    pinecone_key = input("Enter PINECONE_API_KEY: ").strip()
    if pinecone_key:
        env_vars['PINECONE_API_KEY'] = pinecone_key
    
    # PINECONE_INDEX_NAME
    current = env_vars.get('PINECONE_INDEX_NAME', 'medagentica')
    print(f"Current PINECONE_INDEX_NAME: {current}")
    pinecone_index = input("Enter PINECONE_INDEX_NAME [default: medagentica]: ").strip()
    env_vars['PINECONE_INDEX_NAME'] = pinecone_index if pinecone_index else current
    
    # OPENROUTER_API_KEY
    current = env_vars.get('OPENROUTER_API_KEY', '')
    if current:
        print(f"Current OPENROUTER_API_KEY: {current[:10]}...{current[-4:]}")
    openrouter_key = input("Enter OPENROUTER_API_KEY: ").strip()
    if openrouter_key:
        env_vars['OPENROUTER_API_KEY'] = openrouter_key
    
    # OPENROUTER_MODEL
    current = env_vars.get('OPENROUTER_MODEL', 'deepseek/deepseek-chat-v3.1:free')
    print(f"Current OPENROUTER_MODEL: {current}")
    openrouter_model = input("Enter OPENROUTER_MODEL [default: deepseek/deepseek-chat-v3.1:free]: ").strip()
    env_vars['OPENROUTER_MODEL'] = openrouter_model if openrouter_model else current
    
    # Save to .env
    print("\n💾 Saving to .env file...")
    with open(env_file, 'w') as f:
        f.write("# RAG & LLM Evaluation Environment Variables\n")
        f.write("# Generated by setup_evaluation.py\n\n")
        for key, value in env_vars.items():
            f.write(f"{key}={value}\n")
    
    print("✅ Environment variables saved to .env")
    
    # Load into current process
    for key, value in env_vars.items():
        os.environ[key] = value
    
    return env_vars

def verify_setup():
    """Run the setup checker."""
    print_header("🔍 Verifying Setup")
    
    print("Running check_evaluation_setup.py...\n")
    
    try:
        result = subprocess.run(
            [sys.executable, 'check_evaluation_setup.py'],
            capture_output=False
        )
        return result.returncode == 0
    except Exception as e:
        print(f"❌ Error running verification: {e}")
        return False

def main():
    """Main setup function."""
    print("\n" + "="*60)
    print("  🚀 RAG & LLM Evaluation Setup Wizard")
    print("="*60)
    
    # Step 1: Install packages
    install_packages()
    
    # Step 2: Setup environment
    env_vars = setup_env_file()
    
    # Step 3: Verify
    print_header("✅ Setup Complete!")
    
    print("Your configuration:")
    print(f"  • PINECONE_INDEX_NAME: {env_vars.get('PINECONE_INDEX_NAME', 'Not set')}")
    print(f"  • OPENROUTER_MODEL: {env_vars.get('OPENROUTER_MODEL', 'Not set')}")
    
    if env_vars.get('PINECONE_API_KEY'):
        print(f"  • PINECONE_API_KEY: Set ✅")
    else:
        print(f"  • PINECONE_API_KEY: Not set ❌")
    
    if env_vars.get('OPENROUTER_API_KEY'):
        print(f"  • OPENROUTER_API_KEY: Set ✅")
    else:
        print(f"  • OPENROUTER_API_KEY: Not set ❌")
    
    print("\n" + "="*60)
    print("  📋 Next Steps")
    print("="*60 + "\n")
    
    print("1. Load environment variables in your shell:")
    print("   source .env")
    print("   OR (for current session):")
    print("   export $(cat .env | grep -v '^#' | xargs)")
    print("")
    print("2. Verify setup:")
    print("   python check_evaluation_setup.py")
    print("")
    print("3. If Pinecone index is empty, ingest data:")
    print("   python demo_ingest_pinecone.py")
    print("")
    print("4. Run your first evaluation:")
    print("   python quick_evaluate.py")
    print("")
    
    # Ask if user wants to verify now
    verify = input("Would you like to verify the setup now? (y/n): ").strip().lower()
    if verify == 'y':
        success = verify_setup()
        if success:
            print("\n🎉 All checks passed! You're ready to evaluate!")
        else:
            print("\n⚠️  Some checks failed. Please review the output above.")

if __name__ == "__main__":
    main()

